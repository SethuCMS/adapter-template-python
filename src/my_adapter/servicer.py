"""Turns the gRPC protocol into calls on your ``Adapter``.

You normally do not edit this file. It does the safety work that is the same for every adapter:

* one adapter instance per connection id;
* known failures (``AdapterError``) become the protocol's ``Error``; anything else becomes a
  generic ``INTERNAL`` error, so a driver's message can never reach a client;
* nothing sensitive (credentials, config, records) is ever logged.
"""
from __future__ import annotations

import logging
import threading
from typing import Any, Callable, Dict, Optional

from google.protobuf import json_format
from google.protobuf.struct_pb2 import Struct

from .base import Adapter, AdapterError, Capabilities, CollectionInfo, FindResult
from .generated import adapter_pb2 as pb
from .generated import adapter_pb2_grpc as pb_grpc

log = logging.getLogger("my_adapter")


def to_dict(struct: Struct) -> Dict[str, Any]:
    """Struct -> plain dict.

    Protobuf's Struct stores every number as a double, so 3 arrives as 3.0. Whole numbers are
    turned back into ints here. (Whole numbers above 2**53 cannot be represented exactly in a
    Struct; send those as strings.)
    """
    return _whole_numbers(json_format.MessageToDict(struct))


def _whole_numbers(value: Any) -> Any:
    if isinstance(value, float) and value.is_integer() and abs(value) <= 2**53:
        return int(value)
    if isinstance(value, dict):
        return {k: _whole_numbers(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_whole_numbers(v) for v in value]
    return value


def to_struct(data: Optional[Dict[str, Any]]) -> Struct:
    struct = Struct()
    if data:
        json_format.ParseDict(data, struct)
    return struct


def _error(code: str, message: str, details: Optional[Dict[str, Any]] = None) -> pb.Error:
    return pb.Error(code=code, message=message, details=to_struct(details))


class AdapterService(pb_grpc.AdapterServicer):
    def __init__(self, factory: Callable[[], Adapter], adapter_type: str) -> None:
        self._factory = factory
        self._adapter_type = adapter_type
        self._adapters: Dict[str, Adapter] = {}
        self._lock = threading.Lock()

    # -- helpers -------------------------------------------------------------------
    def _adapter(self, connection_id: str) -> Adapter:
        with self._lock:
            adapter = self._adapters.get(connection_id)
        if adapter is None:
            raise AdapterError("CONNECTION_FAILED", "The connection is not open")
        return adapter

    def _guard(self, label: str, run: Callable[[], Any], on_error: Callable[[pb.Error], Any]) -> Any:
        try:
            return run()
        except AdapterError as error:
            return on_error(_error(error.code, error.message, error.details))
        except Exception:  # noqa: BLE001 - deliberate catch-all; the message must not escape
            log.exception("unexpected failure in %s", label)  # stays on this machine
            return on_error(_error("INTERNAL", "The adapter failed unexpectedly"))

    # -- rpc methods ---------------------------------------------------------------
    def Connect(self, request, context):
        def run():
            if request.adapter_type and request.adapter_type != self._adapter_type:
                raise AdapterError("VALIDATION_FAILED", "This server does not handle that adapter type")
            adapter = self._factory()
            adapter.connect(to_dict(request.config), to_dict(request.credentials), request.read_only)
            with self._lock:
                previous = self._adapters.pop(request.connection_id, None)
                self._adapters[request.connection_id] = adapter
            if previous is not None:
                _close_quietly(previous)
            return pb.ConnectResponse(ok=True)

        return self._guard("Connect", run, lambda e: pb.ConnectResponse(ok=False, error=e))

    def Introspect(self, request, context):
        def run():
            collections = self._adapter(request.connection_id).introspect()
            return pb.IntrospectResponse(collections=[_collection_to_pb(c) for c in collections])

        return self._guard("Introspect", run, lambda e: pb.IntrospectResponse(error=e))

    def Capabilities(self, request, context):
        def run():
            return _capabilities_to_pb(self._adapter(request.connection_id).capabilities())

        return self._guard("Capabilities", run, lambda e: pb.CapabilitiesResponse())

    def Find(self, request, context):
        def run():
            result: FindResult = self._adapter(request.connection_id).find(to_dict(request.query))
            return pb.FindResponse(
                records=[to_struct(r) for r in result.records],
                next_cursor=result.next_cursor or "",
                capability_notes=result.notes,
            )

        return self._guard("Find", run, lambda e: pb.FindResponse(error=e))

    def Get(self, request, context):
        def run():
            record = self._adapter(request.connection_id).get(request.collection, request.id)
            if record is None:
                raise AdapterError("NOT_FOUND", "No such record")
            return pb.GetResponse(record=to_struct(record))

        return self._guard("Get", run, lambda e: pb.GetResponse(error=e))

    def Create(self, request, context):
        def run():
            record = self._adapter(request.connection_id).create(request.collection, to_dict(request.values))
            return pb.WriteResponse(record=to_struct(record))

        return self._guard("Create", run, lambda e: pb.WriteResponse(error=e))

    def Update(self, request, context):
        def run():
            record = self._adapter(request.connection_id).update(request.collection, request.id, to_dict(request.values))
            return pb.WriteResponse(record=to_struct(record))

        return self._guard("Update", run, lambda e: pb.WriteResponse(error=e))

    def Delete(self, request, context):
        def run():
            self._adapter(request.connection_id).delete(request.collection, request.id)
            return pb.DeleteResponse(ok=True)

        return self._guard("Delete", run, lambda e: pb.DeleteResponse(ok=False, error=e))

    def Batch(self, request, context):
        # Optional in the protocol. Implement it only if your database can do it safely.
        return pb.BatchResponse(error=_error("CAPABILITY_UNSUPPORTED", "Batch writes are not supported"))

    def Subscribe(self, request, context):
        # Optional in the protocol (realtime). Not supported by this template.
        import grpc

        context.abort(grpc.StatusCode.UNIMPLEMENTED, "Subscribe is not supported")

    def Close(self, request, context):
        with self._lock:
            adapter = self._adapters.pop(request.connection_id, None)
        if adapter is not None:
            _close_quietly(adapter)
        return pb.CloseResponse(ok=True)

    def close_all(self) -> None:
        with self._lock:
            adapters, self._adapters = list(self._adapters.values()), {}
        for adapter in adapters:
            _close_quietly(adapter)


def _close_quietly(adapter: Adapter) -> None:
    try:
        adapter.close()
    except Exception:  # noqa: BLE001
        log.exception("close failed")


def _collection_to_pb(c: CollectionInfo) -> pb.CollectionInfo:
    return pb.CollectionInfo(
        native_name=c.native_name,
        fields=[
            pb.FieldInfo(
                native_name=f.native_name, native_type=f.native_type, canonical_type=f.canonical_type,
                required=f.required, is_primary_key=f.is_primary_key, lossy=f.lossy,
            )
            for f in c.fields
        ],
        relations=[pb.RelationInfo(name=r.name, target=r.target, kind=r.kind, mapping=to_struct(r.mapping)) for r in c.relations],
    )


def _capabilities_to_pb(c: Capabilities) -> pb.CapabilitiesResponse:
    return pb.CapabilitiesResponse(
        joins=c.joins, transactions=c.transactions, filter_or=c.filter_or,
        filter_inequality=c.filter_inequality, full_text=c.full_text, sort=c.sort,
        offset_pagination=c.offset_pagination, aggregations=c.aggregations,
        realtime=c.realtime, schema=c.schema, writes=c.writes,
    )
